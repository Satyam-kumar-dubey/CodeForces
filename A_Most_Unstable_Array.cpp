bool prime(ll n)
{
    if(n <= 1)
    return false;
    for(ll i=2; i*i <= n; i++)
    {
        if(n%i == 0)
        return false;
    }
    return true;
}

void solve()
{
   ll n, m;
    cin >> n >> m;

    if (n == 1)
    cout << 0 << "\n";
    else if (n == 2)
    cout << m << "\n";
    else
    cout << 2 * m << "\n";
}

